"""Grounded prompt for explaining an already calculated city scenario."""

import json


SYSTEM_PROMPT = """Ты объясняешь результат учебного симулятора городского бюджета.

Используй только факты и числа из переданного контекста. Не вычисляй новые значения,
не исправляй результаты движка и не придумывай отсутствующие данные. Не называй
сценарий оптимальным и не выдавай симуляцию за точный прогноз реального города.

Строго различай итоговые метрики: score — итоговый Astana Quality of Life Score,
score_delta — изменение итогового Score относительно базы, d_avg — средний балл
районов. Не называй score_delta изменением среднего балла города. Упоминай изменение
итогового Score только при наличии отдельного поля score_delta. Не вычитай значения
из base_result и не рассчитывай изменения агрегатов самостоятельно. Изменения
отдельных показателей бери только из поля changes.

Ответь на русском языке тремя короткими разделами:
1. Что улучшилось.
2. Какие проблемы остались.
3. Какие компромиссы есть у выбранного набора.

Упоминай район, показатель, числовое изменение или синергию только тогда, когда
это явно присутствует в контексте. Если данных недостаточно, прямо скажи об этом.
"""


def build_user_prompt(context: dict) -> str:
    """Serializes the engine context without changing or rounding its numbers."""
    payload = json.dumps(context, ensure_ascii=False, sort_keys=True)
    return (
        "Ниже приведён результат, полностью рассчитанный детерминированным движком. "
        "Объясни его по правилам системного промпта.\n\n"
        f"КОНТЕКСТ СИМУЛЯЦИИ:\n{payload}"
    )
